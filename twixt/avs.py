"""Generates the AviSynth script that MPC-HC's filter runs.

This is the path SVP itself uses for DirectShow players, and for good reason:
the AviSynth script host is a plain script engine, whereas the VapourSynth one
has to boot an embedded Python interpreter inside the player process -- which
deadlocks on load here.

The interpolation is the same family of algorithm either way: MVTools'
Super -> Analyse -> Recalculate -> FlowFps.
"""

from __future__ import annotations

import os
from pathlib import Path

from .profiles import ARTIFACT_MASKING, GRID, Profile

ROOT = Path(__file__).resolve().parent.parent
AVS_DIR = ROOT / "runtime" / "avisynth"
MVTOOLS_DLL = AVS_DIR / "plugins64" / "mvtools2.dll"

_TEMPLATE = '''# --- generated by twixt -------------------------------------------------------
# Runs inside MPC-HC through the AviSynth Filter. Edit and reopen the video to
# try changes; nothing needs re-registering.

# Load by absolute path rather than relying on a plugin autoload directory.
LoadPlugin("{mvtools}")

# Let AviSynth+ use several threads. The source has to stay serialised.
SetFilterMTMode("DEFAULT_MT_MODE", 2)
SetFilterMTMode("AvsFilterSource", 3)

src = AvsFilterSource()
src = src.ConvertToYV12()

fps = FrameRate(src)

# Whole multiples only: they divide evenly into the display's frame time, and
# the player is left to resample the small remainder.
mult = Int(Min(Float({cap}) / fps, 8.0))
mult = Max(mult, 2)

if (fps > {bypass}) {{
    # Already smooth. Drop out of the filter graph so this costs nothing.
    src
    AvsFilterDisconnect()
}} else {{
    sup = MSuper(src, pel={pel}, hpad={hpad}, vpad={vpad}, sharp=2, rfilter=4)

    bv = MAnalyse(sup, isb=true,  blksize={blk}, overlap={overlap}, \\
                  search={search}, searchparam={searchparam}, \\
                  truemotion=true, dct=0, plevel=0, pnew=50)
    fv = MAnalyse(sup, isb=false, blksize={blk}, overlap={overlap}, \\
                  search={search}, searchparam={searchparam}, \\
                  truemotion=true, dct=0, plevel=0, pnew=50)
{refine}
    res = MFlowFps(src, sup, bv, fv, \\
             num=FramerateNumerator(src) * mult, den=FramerateDenominator(src), \\
             mask=2, ml={ml}, blend={blend}, \\
             thscd1={thscd1}, thscd2=130)
{proof}
    res
    Prefetch({threads})
}}
'''

_REFINE = '''
    # Second pass at half the block size sharpens the vectors on fine detail.
    bv = MRecalculate(sup, bv, blksize={half}, overlap={half_overlap}, \\
                      thsad=200, search={search}, searchparam={searchparam}, \\
                      truemotion=true)
    fv = MRecalculate(sup, fv, blksize={half}, overlap={half_overlap}, \\
                      thsad=200, search={search}, searchparam={searchparam}, \\
                      truemotion=true)
'''


def _even_below(value: int, limit: int) -> int:
    """Overlap must be even and strictly under the block size."""
    return max(2, min(limit - 2, value) // 2 * 2)


# Writes the real input and output frame rates the moment playback starts, so
# "is it actually interpolating" is answered by measurement rather than belief.
_PROOF = '''
    res = WriteFileStart(res, "{path}", \\
        """"source_fps=" + String(FrameRate(src))""", \\
        """" multiplier=" + String(mult)""", \\
        """" output_fps=" + String(FrameRate(res))""", \\
        """" size=" + String(Width(res)) + "x" + String(Height(res))""")
'''


def generate_script(profile: Profile, threads: int | None = None,
                    proof_path: Path | None = None) -> str:
    blk = GRID[profile.grid]
    overlap = _even_below(int(blk * profile.overlap), blk)
    half = max(4, blk // 2)

    refine = ""
    if profile.refine:
        refine = _REFINE.format(
            half=half,
            half_overlap=_even_below(half // 2, half),
            search=5 if profile.wide_search else 3,
            searchparam=profile.search_radius,
        )

    if threads is None:
        threads = min(16, max(2, (os.cpu_count() or 8)))

    proof = _PROOF.format(path=str(proof_path)) if proof_path else ""

    return _TEMPLATE.format(
        proof=proof,
        # AviSynth string literals are taken verbatim -- no escape processing --
        # so the path goes in with single backslashes.
        mvtools=str(MVTOOLS_DLL),
        cap=f"{profile.max_output_fps:g}",
        bypass=f"{profile.bypass_above_fps:g}",
        pel=2, hpad=8, vpad=8,
        blk=blk,
        overlap=overlap,
        search=5 if profile.wide_search else 3,
        searchparam=profile.search_radius,
        refine=refine,
        ml=max(1, ARTIFACT_MASKING[profile.artifact_masking]),
        blend="true" if profile.blend_on_scene_change else "false",
        thscd1=profile.scene_change_threshold,
        threads=threads,
    )


def write_script(profile: Profile, path: Path, threads: int | None = None,
                 proof_path: Path | None = None) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(generate_script(profile, threads, proof_path), encoding="utf-8")
    return path
