"""Launches mpv with the generated filter attached, and talks to it over IPC.

mpv is used because its `vapoursynth` video filter runs the interpolation inside
the playback pipeline -- the same integration point SVP uses. Everything about
the interpolation lives in the generated script; this module only wires it up
and picks the sync flags that let a non-integer frame rate land cleanly on the
panel.
"""

from __future__ import annotations

import json
import os
import subprocess
import tempfile
import time
import uuid
from dataclasses import dataclass
from pathlib import Path

from . import detect
from .engine import write_script
from .profiles import Profile

SCRIPT_DIR = Path(tempfile.gettempdir()) / "twixt"


@dataclass
class Session:
    process: subprocess.Popen
    script: Path
    ipc: str
    source: detect.SourceInfo
    profile: Profile
    target_fps: float

    def wait(self) -> int:
        return self.process.wait()

    # --- live control -------------------------------------------------------

    def command(self, *args) -> dict | None:
        """Send an mpv IPC command. Returns the reply, or None if unreachable."""
        payload = json.dumps({"command": list(args)}) + "\n"
        try:
            if os.name == "nt":
                # self.ipc already holds the full \\.\pipe\... name mpv was given.
                with open(self.ipc, "r+b", buffering=0) as pipe:
                    pipe.write(payload.encode("utf-8"))
                    return json.loads(pipe.readline().decode("utf-8") or "{}")
            import socket
            with socket.socket(socket.AF_UNIX, socket.SOCK_STREAM) as sock:
                sock.connect(self.ipc)
                sock.sendall(payload.encode("utf-8"))
                return json.loads(sock.recv(65536).decode("utf-8") or "{}")
        except Exception:
            return None

    def get(self, prop: str):
        reply = self.command("get_property", prop)
        return reply.get("data") if reply else None

    def set_interpolation(self, enabled: bool) -> None:
        """Add or remove the filter without restarting playback -- an A/B switch."""
        if enabled:
            self.command("vf", "add", self._vf_arg())
        else:
            self.command("vf", "remove", f"@{FILTER_LABEL}")

    def stats(self) -> dict:
        """What the player is actually managing to do right now."""
        return {
            "estimated_vf_fps": self.get("estimated-vf-fps"),
            "container_fps": self.get("container-fps"),
            "display_fps": self.get("display-fps"),
            "frames_dropped": self.get("frame-drop-count"),
            "decoder_dropped": self.get("decoder-frame-drop-count"),
            "time_pos": self.get("time-pos"),
        }

    def _vf_arg(self) -> str:
        return _vf_arg(self.script, self.profile)


FILTER_LABEL = "twixt"


def _vf_arg(script: Path, profile: Profile, labelled: bool = True) -> str:
    # buffered-frames gives the filter a runway so a momentarily slow frame does
    # not become a visible hitch; concurrent-frames is how many it works on at once.
    concurrent = max(1, profile.num_streams)
    buffered = max(4, concurrent * 2)
    # The label lets us toggle this exact filter at runtime without disturbing
    # anything else in the chain.
    prefix = f"@{FILTER_LABEL}:" if labelled else ""
    return (
        f"{prefix}vapoursynth=file={_escape(script)}"
        f":buffered-frames={buffered}"
        f":concurrent-frames={concurrent}"
    )


def write_input_conf(script: Path, profile: Profile, path: Path) -> Path:
    """Key bindings for comparing interpolated against original, live.

    Toggling needs the full filter definition because mpv has to be able to add
    it back, not just remove it.
    """
    vf = _vf_arg(script, profile)
    lines = [
        "# generated by twixt",
        f'TAB vf toggle {vf}; show-text "interpolation: toggled" 1500',
        'i script-binding stats/display-stats-toggle',
        'BS show-text "${estimated-vf-fps} fps out / ${container-fps} fps in  '
        'dropped: ${frame-drop-count}" 3000',
    ]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def _escape(path: Path) -> str:
    """Quote a path for an mpv filter argument.

    Windows paths carry both ':' and '\\', which mpv reads as separators.
    Rather than escape each one, use mpv's length-prefixed literal form
    (%<bytes>%<text>), which passes any string through untouched.
    """
    text = str(path)
    return f"%{len(text.encode('utf-8'))}%{text}"


def build_args(source: detect.SourceInfo, profile: Profile, script: Path,
               ipc: str, extra: list[str] | None = None,
               input_conf: Path | None = None) -> list[str]:
    mpv = detect.mpv_path()
    args = [
        str(mpv) if mpv else "mpv",
        str(source.path),

        f"--vf={_vf_arg(script, profile)}",

        # The vapoursynth filter needs frames in system memory, so hardware
        # decoding has to stay off. Decoding is cheap next to interpolation.
        "--hwdec=no",

        # Resample the audio clock to the display instead of dropping/repeating
        # frames. Without this a 179.82 fps output on a 180 Hz panel judders.
        "--video-sync=display-resample",

        # mpv's own frame blending would fight our interpolation.
        "--interpolation=no",

        "--vo=gpu-next",
        "--profile=high-quality",
        "--keep-open=yes",
        f"--input-ipc-server={ipc}",
        "--term-status-msg=",
    ]
    if input_conf:
        args.append(f"--input-conf={input_conf}")
    if extra:
        args.extend(extra)
    return args


def launch(source_path: str | Path, profile: Profile,
           extra_mpv_args: list[str] | None = None,
           dry_run: bool = False) -> Session | list[str]:
    """Probe the file, generate its filter script, and start playback."""
    mpv = detect.mpv_path()
    if not mpv and not dry_run:
        raise RuntimeError(
            "mpv not found. Run bootstrap.ps1 to install the runtime, or put mpv on PATH."
        )

    info = detect.probe(source_path)
    display_fps = detect.display_refresh_hz()
    target = profile.resolve_target_fps(info.fps, display_fps)

    SCRIPT_DIR.mkdir(parents=True, exist_ok=True)
    script = SCRIPT_DIR / f"{Path(source_path).stem[:40]}-{uuid.uuid4().hex[:8]}.vpy"
    write_script(profile, script, info.fps, display_fps,
                 standalone_source=str(Path(source_path).resolve()),
                 matrix=info.matrix)

    token = uuid.uuid4().hex[:8]
    # On Windows mpv expects the fully qualified named-pipe path.
    ipc = ("\\\\.\\pipe\\twixt-" + token if os.name == "nt"
           else str(SCRIPT_DIR / f"ipc-{token}.sock"))

    conf = write_input_conf(script, profile, script.with_suffix(".conf"))
    args = build_args(info, profile, script, ipc, extra_mpv_args, input_conf=conf)

    if dry_run:
        return args

    process = subprocess.Popen(args, env=detect.player_env())
    return Session(process=process, script=script, ipc=ipc,
                   source=info, profile=profile, target_fps=target)


# --- capability check -------------------------------------------------------

def benchmark(source_path: str | Path, profile: Profile,
              frames: int = 240, start_frame: int | None = None) -> dict:
    """Render a chunk through the real filter chain and measure throughput.

    This answers the only question that matters before you press play: can this
    machine sustain the target rate, or will it stutter?
    """
    vspipe = detect.vspipe_path()
    if not vspipe:
        raise RuntimeError("vspipe not found. Run bootstrap.ps1 first.")

    info = detect.probe(source_path)
    display_fps = detect.display_refresh_hz()
    target = profile.resolve_target_fps(info.fps, display_fps)

    SCRIPT_DIR.mkdir(parents=True, exist_ok=True)
    script = SCRIPT_DIR / f"bench-{uuid.uuid4().hex[:8]}.vpy"
    write_script(profile, script, info.fps, display_fps,
                 standalone_source=str(Path(source_path).resolve()),
                 matrix=info.matrix)

    # Sample from the middle by default. The opening frames of a film are
    # usually black or a static logo, which motion estimation chews through far
    # faster than real footage -- benchmarking them overstates what will hold.
    if start_frame is None:
        total = int(info.duration * info.fps) if info.duration else 0
        start_frame = max(0, int(total * 0.4)) if total > frames * 4 else 0

    start = time.perf_counter()
    proc = subprocess.run(
        [str(vspipe), "-c", "y4m",
         "-s", str(start_frame), "-e", str(start_frame + frames - 1),
         str(script), os.devnull],
        capture_output=True, text=True, env=detect.player_env(), timeout=1200,
    )
    elapsed = time.perf_counter() - start
    script.unlink(missing_ok=True)

    if proc.returncode != 0:
        raise RuntimeError(f"vspipe failed:\n{proc.stderr.strip()[:2000]}")

    achieved = frames / elapsed if elapsed > 0 else 0.0
    return {
        "source_fps": info.fps,
        "target_fps": target,
        "achieved_fps": achieved,
        "realtime": achieved >= target,
        "headroom": (achieved / target) if target else 0.0,
        "resolution": f"{info.width}x{info.height}",
        "elapsed": elapsed,
        "frames": frames,
        "start_frame": start_frame,
    }
