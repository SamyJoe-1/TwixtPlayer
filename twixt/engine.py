def _pick_rife_model(preferred):
    """Use the requested revision if present, else the newest one that is.

    The model pack ships a different set of revisions over time, and asking for
    a missing one is a hard failure at play time.
    """
    have = _available_rife_models()
    if not have or preferred in have:
        return preferred
    return max(have)


def _mark_scene_changes(c):
    """Flag cuts so RIFE repeats a frame instead of morphing across them.

    Without this, every hard cut becomes a smear of one shot melting into the
    next -- the single most objectionable interpolation artifact.
    """
    try:
        # Only a per-frame yes/no comes out of this -- no vectors are reused --
        # so it can run on a small copy (unlike FlowFPS, which needs vectors of
        # the clip it renders). thSCD1 is normalised to 8x8 blocks (MVTools2
        # docs), so the threshold keeps its meaning. At 1440p this is ~7x fewer
        # pixels through Super/Analyse for the same cut decisions.
        if c.width > CFG["scene_detect_width"]:
            w = CFG["scene_detect_width"]
            h = max(2, int(round(c.height * w / c.width / 2)) * 2)
            c = core.resize.Bilinear(c, width=w, height=h)
        sup = core.mv.Super(c, pel=1, sharp=0, rfilter=2)
        vec = core.mv.Analyse(sup, isb=True, blksize=16, overlap=0, search=0)
        return core.mv.SCDetection(
            c, vec,
            thscd1=CFG["scene_change_threshold"], thscd2=CFG["scene_change_ratio"],
        )
    except Exception:
        # Scene detection is a quality guard, not a requirement; if mvtools is
        # unavailable carry on rather than refusing to play.
        return c


def _rife_pad_multiple(model_id):
    """Frame-size multiple vsmlrt.RIFEMerge insists on for this revision.

    Mirrors vsmlrt.py: 4.26 (and heavy variants) need 64, 4.25 lite 128,
    everything older 32. Asking a 64-multiple model to run on 1440 rows fails
    with "tile size must be divisible by 64".
    """
    text = str(int(model_id))
    major, minor = int(text[0]), int(text[1:3])
    suffix = text[3:] if len(text) >= 4 else ""
    if (major, minor) == (4, 25) and suffix == "1":
        return 128
    if (major, minor) >= (4, 26) or ((major, minor) == (4, 25) and suffix == "2"):
        return 64
    return 32


def _select_unless_cut(interp, left):
    """Per frame: the interpolated frame, or `left` if a cut follows it.

    akarin.Select is native; std.FrameEval is the fallback and runs a Python
    callback per frame, which is exactly the GIL bottleneck this graph exists
    to avoid -- install the akarin plugin (bootstrap does).
    """
    if hasattr(core, "akarin") and hasattr(core.akarin, "Select"):
        return core.akarin.Select([interp, left], left, "x._SceneChangeNext 1 0 ?")

    def pick(n, f):
        return left if f.props.get("_SceneChangeNext") else interp
    return core.std.FrameEval(interp, pick, prop_src=left)


def _every(clip, cycle, offset):
    """SelectEvery that also accepts cycle=1 (std.SelectEvery refuses it)."""
    return clip if cycle == 1 else core.std.SelectEvery(clip, cycle=cycle, offsets=offset)


def _rife_native(c, multi, merge):
    """Interpolate `c` by the rational `multi` with native filters only.

    vsmlrt.RIFE's own fractional path for video players builds the frame
    pairs with three std.FrameEval Python callbacks per OUTPUT frame, one of
    which creates a brand-new BlankClip node every time. Those callbacks
    serialise on the Python GIL, so no matter how many frames mpv asks for at
    once the GPU is fed one tiny burst at a time -- the measured ~13% GPU load
    and the "concurrency saturates at 2" behaviour.

    A p/q multiplier is periodic: every p output frames span exactly q source
    frames, and output phase j (0..p-1) always sits between source frames
    floor(j*q/p) and +1 of its cycle, at time (j*q mod p)/p. So each phase is a
    plain SelectEvery of the source, the time masks are p constant frames
    looped, and the whole graph is SelectEvery/Interleave/Loop -- C++ only,
    fully parallel, nothing evaluated per frame in Python.
    """
    p, q = multi.numerator, multi.denominator
    gray = vs.GRAYH if c.format.bits_per_sample == 16 else vs.GRAYS
    nxt = core.std.Trim(core.std.DuplicateFrames(c, frames=[c.num_frames - 1]), first=1)

    phases = []
    for j in range(p):
        offset, remainder = divmod(j * q, p)
        phases.append((offset, Fraction(remainder, p)))

    moving = [(o, tp) for o, tp in phases if tp != 0]
    left = core.std.Interleave(
        [_every(c, q, o) for o, _ in moving],
        extend=True, mismatch=True, modify_duration=False)
    right = core.std.Interleave(
        [_every(nxt, q, o) for o, _ in moving],
        extend=True, mismatch=True, modify_duration=False)
    mask = core.std.Interleave(
        [core.std.BlankClip(left, format=gray, color=float(tp), length=1, keep=True)
         for _, tp in moving],
        modify_duration=False)
    mask = core.std.Trim(core.std.Loop(mask, times=-(-left.num_frames // len(moving))),
                         length=left.num_frames)

    interp = merge(left, right, mask)
    if interp.format.id != c.format.id:
        c = core.resize.Point(c, format=interp.format.id)
        left = core.resize.Point(left, format=interp.format.id)
    interp = _select_unless_cut(interp, left)

    out_phases, k = [], 0
    for offset, tp in phases:
        if tp == 0:
            out_phases.append(_every(c, q, offset))
        else:
            out_phases.append(_every(interp, len(moving), k))
            k += 1
    out = core.std.Interleave(out_phases, extend=True, mismatch=True, modify_duration=False)
    rate = c.fps * multi
    return core.std.AssumeFPS(out, fpsnum=rate.numerator, fpsden=rate.denominator)


def _interp_rife(c):
    """Neural flow interpolation on the GPU -- what SVP's RIFE mode runs too."""
    fmt = c.format

    # Detect cuts while the clip is still YUV8 (what mvtools accepts); the
    # frame properties survive the conversion to RGB below.
    if CFG["scene_detection"]:
        detect_src = c
        if fmt.bits_per_sample != 8 or fmt.color_family != vs.YUV:
            detect_src = core.resize.Bicubic(c, format=vs.YUV420P8)
        marked = _mark_scene_changes(detect_src)
        c = core.std.CopyFrameProps(c, marked)

    try:
        import vsmlrt
    except ImportError:
        vsmlrt = None

    # fp16 RGB when the engine runs fp16: half the bytes of RGBS through every
    # conversion and every host->device copy, and vsmlrt accepts it directly.
    rgb = vs.RGBH if (vsmlrt and CFG["rife_fp16"]) else vs.RGBS
    c = core.resize.Bicubic(c, format=rgb, matrix_in_s=CFG["matrix"])

    model = _pick_rife_model(CFG["rife_model_id"]) if vsmlrt else 0
    multiple = _rife_pad_multiple(model) if vsmlrt else 32

    # RIFE needs both dimensions padded to its multiple. Extend the edge pixels
    # rather than adding black bars: a hard black border would create a false
    # high-contrast edge for the flow estimator and smear the outermost rows.
    pad_w = (-c.width) % multiple
    pad_h = (-c.height) % multiple
    if pad_w or pad_h:
        c = core.resize.Point(
            c,
            width=c.width + pad_w, height=c.height + pad_h,
            src_width=c.width + pad_w, src_height=c.height + pad_h,
        )

    if vsmlrt:
        backend = getattr(vsmlrt.Backend, CFG["rife_backend"])(
            **CFG["rife_backend_options"]
        )

        def merge(a, b, m):
            return vsmlrt.RIFEMerge(
                a, b, m,
                model=model, backend=backend,
                scale=CFG["rife_scale"], ensemble=CFG["rife_ensemble"],
            )

        c = _rife_native(c, MULTI, merge)
    else:
        # ncnn/Vulkan fallback: no TensorRT engine build step, a bit slower.
        c = core.rife.RIFE(
            c,
            model=CFG["rife_ncnn_model"],
            factor_num=MULTI.numerator,
            factor_den=MULTI.denominator,
            gpu_id=0,
            gpu_thread=CFG["num_streams"],
            sc=True,     # detect scene cuts, do not warp across them
            skip=True,   # reuse frames on static scenes, saves GPU
        )

    if pad_w or pad_h:
        c = core.std.Crop(c, right=pad_w, bottom=pad_h)

    return core.resize.Bicubic(c, format=fmt.id, matrix_s=CFG["matrix"])


def _interp_mvtools(c):
    """Classic block motion estimation -- the open ancestor of SVPflow."""
    fmt = c.format
    if fmt.bits_per_sample != 8 or fmt.color_family != vs.YUV:
        c = core.resize.Bicubic(c, format=vs.YUV420P8)

    blk = CFG["block_size"]
    # Overlap must be even and strictly smaller than the block.
    overlap = max(2, min(blk - 2, int(blk * CFG["overlap"])) // 2 * 2)

    # "Estimate motion on a downscaled copy, apply to full-resolution frames"
    # does not work in mvtools and never did: a vector clip carries the block
    # geometry of whatever it was analysed on, so handing half-height vectors
    # to FlowFPS on the full clip fails outright with "inconsistent source and
    # vector frame size". There is no vector-rescaling filter in this plugin to
    # bridge the two.
    #
    # So estimate at full resolution and buy the speed back where it is
    # actually available: pel=1 skips building the sub-pixel interpolated
    # planes of the Super, which is the expensive half of it, and costs only
    # whole-pixel vector precision -- far less visible than the frame drops it
    # prevents. Grid size (`grid`) and `refine` are the other two levers, and
    # both are measured by `twixt tune`.
    pel = 1 if (CFG["estimate_height"] and c.height > CFG["estimate_height"]) else CFG["pel"]

    sup_est = core.mv.Super(c, pel=pel, sharp=2, rfilter=4)
    sup_full = sup_est

    common = dict(
        blksize=blk, overlap=overlap,
        search=5 if CFG["wide_search"] else 3,
        searchparam=CFG["search_radius"],
        truemotion=True, dct=0, plevel=0, pnew=50,
    )
    bvec = core.mv.Analyse(sup_est, isb=True, **common)
    fvec = core.mv.Analyse(sup_est, isb=False, **common)

    if CFG["refine"]:
        half = max(4, blk // 2)
        rec = dict(
            blksize=half, overlap=max(2, min(half - 2, half // 2) // 2 * 2),
            search=3, searchparam=CFG["search_radius"],
            truemotion=True, thsad=200,
        )
        bvec = core.mv.Recalculate(sup_est, bvec, **rec)
        fvec = core.mv.Recalculate(sup_est, fvec, **rec)

    # Exact rational rate (e.g. 24000/1001 * 15/4), not a value rounded to
    # 1/1000, so the generated time positions repeat with a fixed cadence.
    rate = c.fps * MULTI

    out = core.mv.FlowFPS(
        c, sup_full, bvec, fvec,
        num=rate.numerator, den=rate.denominator,
        mask=2,
        ml=CFG["mvtools_ml"],
        blend=CFG["blend_on_scene_change"],
        thscd1=CFG["scene_change_threshold"],
        thscd2=CFG["scene_change_ratio"],
    )

    if CFG["motion_blur"] > 0:
        out = core.mv.FlowBlur(
            out, sup_full, bvec, fvec, blur=CFG["motion_blur"] * 100
        )

    # Hand the 8-bit result to mpv as it is. Converting back to the source
    # format (10-bit for most AV1/HEVC) ran a full-frame resize on every OUTPUT
    # frame -- 120 times a second at 1440p -- and restored nothing: the extra
    # bits were already discarded on the way in. mpv takes yuv420p natively.
    return out


def _interp_svpflow(c):
    """SVPflow proper, used when the SVP libraries are present on this system."""
    fmt = c.format
    if fmt.bits_per_sample != 8 or fmt.color_family != vs.YUV:
        c = core.resize.Bicubic(c, format=vs.YUV420P8)

    sup = core.svp1.Super(c, json.dumps(CFG["svp_super"]))
    vec = core.svp1.Analyse(sup["clip"], sup["data"], c, json.dumps(CFG["svp_analyse"]))
    smooth = dict(CFG["svp_smooth"])
    smooth["rate"] = {"num": MULTI.numerator, "den": MULTI.denominator}

    out = core.svp2.SmoothFps(
        c, sup["clip"], sup["data"], vec["clip"], vec["data"],
        json.dumps(smooth), src=c, fps=src_fps,
    )
    rate = c.fps * MULTI
    out = core.std.AssumeFPS(out, fpsnum=rate.numerator, fpsden=rate.denominator)
    return out   # 8-bit straight to mpv; see _interp_mvtools


# --- enhance ----------------------------------------------------------------

def _enhance(c):
    """Clean up and upscale the source before interpolation.

    Runs at the source rate (24 fps), not the output rate, so the network only
    sees each real frame once; the interpolator then works on the clean frames.
    """
    mode = CFG["enhance"]
    if mode == "off" or c.height * 2 > CFG["enhance_max_height"]:
        return c
    import vsmlrt
    fmt = c.format
    backend = vsmlrt.Backend.TRT(
        fp16=True, num_streams=2, use_cuda_graph=True,
        output_format=1,  # fp16 out
    )
    x = core.resize.Bicubic(c, format=vs.RGBH, matrix_in_s=CFG["matrix"])
    if mode == "deblock+upscale":
        x = vsmlrt.DPIR(
            x, strength=CFG["deblock_strength"],
            model=vsmlrt.DPIRModel.drunet_deblocking_color, backend=backend,
        )
    x = vsmlrt.RealESRGAN(
        x, model=vsmlrt.RealESRGANModel.animevideo_xsx2, backend=backend,
    )
    return core.resize.Bicubic(x, format=fmt.id, matrix_s=CFG["matrix"],
                               dither_type="error_diffusion")


