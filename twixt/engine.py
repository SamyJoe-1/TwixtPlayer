"""Generates the VapourSynth script that performs the interpolation.

The generated .vpy is loaded by mpv as a video filter, so it runs inside the
playback pipeline frame by frame -- that is what makes this real time rather
than a batch re-encode.

The output is written as readable, self-contained Python on purpose: when a
profile misbehaves the script can be opened, tweaked and re-run through vspipe
without touching this generator.
"""

from __future__ import annotations

import json
import pprint
from pathlib import Path

from .detect import plugin_dirs
from .profiles import ARTIFACT_MASKING, GRID, Profile

_HEADER = '''# --- generated by twixt, do not hand-edit unless you mean it -------------------
import json
import math
import vapoursynth as vs
from fractions import Fraction

core = vs.core
CFG = {cfg}

def _load_plugins():
    """Load our plugins explicitly instead of relying on autoload.

    VapourSynth's portable autoload keys off the location of the core library,
    which the R79 wheel layout moved inside site-packages. Loading by absolute
    path sidesteps that entirely and fails loudly rather than silently.
    """
    import os

    loaded, failed = [], []
    for directory in CFG["plugin_dirs"]:
        if not directory or not os.path.isdir(directory):
            continue
        for name in sorted(os.listdir(directory)):
            if not name.lower().endswith(".dll"):
                continue
            try:
                core.std.LoadPlugin(os.path.join(directory, name))
                loaded.append(name)
            except Exception as exc:
                # Already registered, or a support DLL rather than a plugin.
                if "already" not in str(exc).lower():
                    failed.append(name + ": " + str(exc))
    return loaded, failed


_LOADED, _FAILED = _load_plugins()


def _open_source(path):
    """Open a file with whichever source filter this install actually has.

    Playback never reaches here -- mpv hands frames straight to the filter.
    This is only for vspipe runs such as `twixt bench`.
    """
    attempts = (
        ("bs", lambda: core.bs.VideoSource(source=path)),
        ("lsmas", lambda: core.lsmas.LWLibavSource(source=path)),
        ("ffms2", lambda: core.ffms2.Source(source=path)),
    )
    errors = []
    for name, factory in attempts:
        try:
            return factory()
        except Exception as exc:
            errors.append(name + ": " + str(exc))
    raise RuntimeError(
        "no usable source filter. Tried " + "; ".join(errors)
    )


# This script runs in three different hosts, each of which supplies the source
# clip its own way:
#   "dshow"      VapourSynth Filter inside MPC-HC and other DirectShow players
#   "mpv"        mpv's vapoursynth video filter
#   "standalone" vspipe, for `twixt bench`
if "VpsFilterSource" in globals():
    _HOST = "dshow"
    clip = VpsFilterSource                                 # noqa: F821
    src_fps = float(clip.fps) or CFG["assumed_fps"]
    disp_fps = CFG["display_fps"]
elif "video_in" in globals():
    _HOST = "mpv"
    clip = video_in                                        # noqa: F821
    src_fps = float(container_fps) or CFG["assumed_fps"]   # noqa: F821
    disp_fps = float(display_fps) or CFG["display_fps"]    # noqa: F821
else:
    _HOST = "standalone"
    clip = _open_source(CFG["standalone_source"])
    src_fps = float(clip.fps) or CFG["assumed_fps"]
    disp_fps = CFG["display_fps"]

# mpv passes frames through without frame-rate metadata, but MVTools refuses to
# run on a clip that has none ("FlowFPS: The input clip must have a frame rate").
# Stamp the container rate on so the graph matches what vspipe sees.
if clip.fps.numerator == 0 or clip.fps.denominator == 0:
    _rate = Fraction(src_fps).limit_denominator(1000000)
    clip = core.std.AssumeFPS(clip, fpsnum=_rate.numerator, fpsden=_rate.denominator)
'''

_BODY = '''

def _target_multiplier():
    """Recompute the ratio at runtime -- the real fps may differ from the probe."""
    if CFG["rate_mode"] == "display":
        target = disp_fps
    elif CFG["rate_mode"] == "multiple":
        target = src_fps * float(Fraction(CFG["rate_multiplier"]))
    else:
        target = CFG["rate_fixed"]
    target = min(target, CFG["max_output_fps"])
    exact = target / src_fps if src_fps > 0 else 2.0
    if exact <= 1.0:
        return Fraction(1)
    # Bias downward: overshooting the panel makes the player drop frames,
    # which reintroduces exactly the judder we are here to remove.
    for denom in range(1, 17):
        cand = Fraction(math.floor(exact * denom), denom)
        if cand >= 1 and (exact - float(cand)) / exact <= 0.02:
            return cand
    return Fraction(exact).limit_denominator(16)


MULTI = _target_multiplier()


def _bypass():
    """Skip interpolation when it would not help or cannot help."""
    if src_fps > CFG["bypass_above_fps"]:
        return "source is already high frame rate"
    if MULTI <= 1:
        return "target rate is not above source rate"
    return None


# --- backends ---------------------------------------------------------------

def _available_rife_models():
    """Map model id -> version string for every RIFE net actually on disk."""
    import os

    found = {}
    for directory in CFG["plugin_dirs"]:
        rife_dir = os.path.join(directory, "models", "rife")
        if not os.path.isdir(rife_dir):
            continue
        for name in os.listdir(rife_dir):
            if not (name.startswith("rife_v") and name.endswith(".onnx")):
                continue
            version = name[len("rife_v"):-len(".onnx")]
            if "_" in version:      # variants such as 4.12_lite
                continue
            try:
                found[int(version.replace(".", ""))] = version
            except ValueError:
                pass
    return found


def _pick_rife_model(preferred):
    """Use the requested revision if present, else the newest one that is.

    The model pack ships a different set of revisions over time, and asking for
    a missing one is a hard failure at play time.
    """
    have = _available_rife_models()
    if not have or preferred in have:
        return preferred
    return max(have)


def _mark_scene_changes(c):
    """Flag cuts so RIFE repeats a frame instead of morphing across them.

    Without this, every hard cut becomes a smear of one shot melting into the
    next -- the single most objectionable interpolation artifact.
    """
    try:
        sup = core.mv.Super(c, pel=1, sharp=0, rfilter=2)
        vec = core.mv.Analyse(sup, isb=True, blksize=32, overlap=0, search=0)
        return core.mv.SCDetection(
            c, vec,
            thscd1=CFG["scene_change_threshold"], thscd2=90,
        )
    except Exception:
        # Scene detection is a quality guard, not a requirement; if mvtools is
        # unavailable carry on rather than refusing to play.
        return c


def _interp_rife(c):
    """Neural flow interpolation. Highest quality, needs a capable GPU."""
    fmt = c.format

    # Detect cuts while the clip is still YUV8 (what mvtools accepts); the
    # frame properties survive the conversion to RGB below.
    if CFG["scene_detection"]:
        detect_src = c
        if fmt.bits_per_sample != 8 or fmt.color_family != vs.YUV:
            detect_src = core.resize.Bicubic(c, format=vs.YUV420P8)
        marked = _mark_scene_changes(detect_src)
        c = core.std.CopyFrameProps(c, marked)

    c = core.resize.Bicubic(c, format=vs.RGBS, matrix_in_s=CFG["matrix"])

    # RIFE's network requires both dimensions to be multiples of 32 (1080 is
    # not). Pad by extending the edge pixels rather than adding black bars: a
    # hard black border would create a false high-contrast edge for the flow
    # estimator and smear the outermost rows of every generated frame.
    pad_w = (-c.width) % 32
    pad_h = (-c.height) % 32
    if pad_w or pad_h:
        c = core.resize.Point(
            c,
            width=c.width + pad_w, height=c.height + pad_h,
            src_width=c.width + pad_w, src_height=c.height + pad_h,
        )

    try:
        import vsmlrt
        backend = getattr(vsmlrt.Backend, CFG["rife_backend"])(
            **CFG["rife_backend_options"]
        )
        c = vsmlrt.RIFE(
            c,
            multi=MULTI,
            model=_pick_rife_model(CFG["rife_model_id"]),
            backend=backend,
            scale=CFG["rife_scale"],
            ensemble=CFG["rife_ensemble"],
            video_player=CFG["rife_low_latency"],
        )
    except ImportError:
        # ncnn/Vulkan fallback: no TensorRT engine build step, a bit slower.
        c = core.rife.RIFE(
            c,
            model=CFG["rife_ncnn_model"],
            factor_num=MULTI.numerator,
            factor_den=MULTI.denominator,
            gpu_id=0,
            gpu_thread=CFG["num_streams"],
            sc=True,     # detect scene cuts, do not warp across them
            skip=True,   # reuse frames on static scenes, saves GPU
        )

    if pad_w or pad_h:
        c = core.std.Crop(c, right=pad_w, bottom=pad_h)

    return core.resize.Bicubic(c, format=fmt.id, matrix_s=CFG["matrix"])


def _interp_mvtools(c):
    """Classic block motion estimation -- the open ancestor of SVPflow."""
    fmt = c.format
    if fmt.bits_per_sample != 8 or fmt.color_family != vs.YUV:
        c = core.resize.Bicubic(c, format=vs.YUV420P8)

    blk = CFG["block_size"]
    # Overlap must be even and strictly smaller than the block.
    overlap = max(2, min(blk - 2, int(blk * CFG["overlap"])) // 2 * 2)

    # "Estimate motion on a downscaled copy, apply to full-resolution frames"
    # does not work in mvtools and never did: a vector clip carries the block
    # geometry of whatever it was analysed on, so handing half-height vectors
    # to FlowFPS on the full clip fails outright with "inconsistent source and
    # vector frame size". There is no vector-rescaling filter in this plugin to
    # bridge the two.
    #
    # So estimate at full resolution and buy the speed back where it is
    # actually available: pel=1 skips building the sub-pixel interpolated
    # planes of the Super, which is the expensive half of it, and costs only
    # whole-pixel vector precision -- far less visible than the frame drops it
    # prevents. Grid size (`grid`) and `refine` are the other two levers, and
    # both are measured by `twixt tune`.
    pel = 1 if (CFG["estimate_height"] and c.height > CFG["estimate_height"]) else CFG["pel"]

    sup_est = core.mv.Super(c, pel=pel, sharp=2, rfilter=4)
    sup_full = sup_est

    common = dict(
        blksize=blk, overlap=overlap,
        search=5 if CFG["wide_search"] else 3,
        searchparam=CFG["search_radius"],
        truemotion=True, dct=0, plevel=0, pnew=50,
    )
    bvec = core.mv.Analyse(sup_est, isb=True, **common)
    fvec = core.mv.Analyse(sup_est, isb=False, **common)

    if CFG["refine"]:
        half = max(4, blk // 2)
        rec = dict(
            blksize=half, overlap=max(2, min(half - 2, half // 2) // 2 * 2),
            search=3, searchparam=CFG["search_radius"],
            truemotion=True, thsad=200,
        )
        bvec = core.mv.Recalculate(sup_est, bvec, **rec)
        fvec = core.mv.Recalculate(sup_est, fvec, **rec)

    num = int(round(src_fps * float(MULTI) * 1000))
    den = 1000

    out = core.mv.FlowFPS(
        c, sup_full, bvec, fvec,
        num=num, den=den,
        mask=2,
        ml=max(1, CFG["artifact_ml"]),
        blend=CFG["blend_on_scene_change"],
        thscd1=CFG["scene_change_threshold"],
        thscd2=90,
    )

    if CFG["motion_blur"] > 0:
        out = core.mv.FlowBlur(
            out, sup_full, bvec, fvec, blur=CFG["motion_blur"] * 100
        )

    return out if out.format.id == fmt.id else core.resize.Bicubic(out, format=fmt.id)


def _interp_svpflow(c):
    """SVPflow proper, used when the SVP libraries are present on this system."""
    fmt = c.format
    if fmt.bits_per_sample != 8 or fmt.color_family != vs.YUV:
        c = core.resize.Bicubic(c, format=vs.YUV420P8)

    sup = core.svp1.Super(c, json.dumps(CFG["svp_super"]))
    vec = core.svp1.Analyse(sup["clip"], sup["data"], c, json.dumps(CFG["svp_analyse"]))
    smooth = dict(CFG["svp_smooth"])
    smooth["rate"] = {"num": MULTI.numerator, "den": MULTI.denominator}

    out = core.svp2.SmoothFps(
        c, sup["clip"], sup["data"], vec["clip"], vec["data"],
        json.dumps(smooth), src=c, fps=src_fps,
    )
    out = core.std.AssumeFPS(
        out, fpsnum=int(round(src_fps * float(MULTI) * 1000)), fpsden=1000
    )
    return out if out.format.id == fmt.id else core.resize.Bicubic(out, format=fmt.id)


# --- assemble ---------------------------------------------------------------

BACKENDS = {"rife": _interp_rife, "mvtools": _interp_mvtools, "svpflow": _interp_svpflow}

_reason = _bypass()

if _reason and _HOST == "dshow":
    # Tell the DirectShow filter to drop itself out of the graph entirely, so a
    # 60 fps source costs nothing rather than being copied through untouched.
    VpsFilterDisconnect = True
else:
    out = clip if _reason else BACKENDS[CFG["backend"]](clip)
    out.set_output()
'''


def _rife_model_id(version: str) -> int:
    """'4.26' -> 426, which is how vs-mlrt enumerates RIFE revisions."""
    return int(str(version).replace(".", ""))


def build_config(profile: Profile, source_fps: float, display_fps: float,
                 standalone_source: str | None = None,
                 matrix: str = "709") -> dict:
    """Flatten a Profile into the plain dict the generated script consumes."""
    blk = GRID[profile.grid]
    return {
        "backend": profile.backend,
        "rate_mode": profile.rate_mode,
        "rate_multiplier": profile.rate_multiplier,
        "rate_fixed": profile.rate_fixed,
        "max_output_fps": profile.max_output_fps,
        "bypass_above_fps": profile.bypass_above_fps,
        "assumed_fps": source_fps or 23.976,
        "display_fps": display_fps,
        "matrix": matrix,
        "standalone_source": standalone_source or "",
        "plugin_dirs": [str(d) for d in plugin_dirs()],

        # rife
        "rife_model_id": _rife_model_id(profile.rife_model),
        "rife_ncnn_model": 9,
        "rife_backend": "TRT",
        "rife_scale": profile.rife_scale,
        "rife_ensemble": profile.rife_ensemble,
        "rife_fp16": profile.rife_fp16,
        "rife_low_latency": profile.rife_low_latency,
        "rife_backend_options": {
            "fp16": profile.rife_fp16,
            "num_streams": profile.num_streams,
            "use_cuda_graph": profile.trt_cuda_graph,
            "output_format": 1 if profile.trt_fp16_output else 0,
            "workspace": profile.trt_workspace_mb,
            "builder_optimization_level": profile.trt_optimization_level,
        },
        "num_streams": profile.num_streams,

        # motion estimation
        "block_size": blk,
        "overlap": profile.overlap,
        "search_radius": profile.search_radius,
        "wide_search": profile.wide_search,
        "refine": profile.refine,
        "pel": 2,
        "estimate_height": profile.downscale_above_height,
        "artifact_ml": ARTIFACT_MASKING[profile.artifact_masking],
        "scene_change_threshold": profile.scene_change_threshold,
        "scene_detection": profile.scene_detection,
        "blend_on_scene_change": profile.blend_on_scene_change,
        "motion_blur": profile.motion_blur,

        # svpflow parameter blocks, in the shape its DLLs expect
        "svp_super": {
            "pel": 2, "gpu": 1,
            "scale": {"up": 0, "down": 4},
            "rc": True,
        },
        "svp_analyse": {
            "gpu": 1,
            "vectors": 3,
            "block": {"w": blk, "h": blk, "overlap": 2},
            "main": {
                "search": {
                    "type": 4 if profile.wide_search else 2,
                    "distance": -(profile.search_radius + 7),
                    "coarse": {
                        "type": 4, "distance": -6,
                        "satd": True, "trymany": profile.wide_search,
                        "bad": {"sad": 2000, "range": 24},
                    },
                },
                "penalty": {"lambda": 10.0, "plevel": 1.5, "lsad": 8000,
                            "pnew": 50, "pglobal": 50, "pzero": 100, "pnbour": 50},
            },
            "refine": [{"thsad": 250}] if profile.refine else [],
        },
        "svp_smooth": {
            "algo": 23,
            "mask": {"area": ARTIFACT_MASKING[profile.artifact_masking]},
            "scene": {
                "mode": 3 if profile.blend_on_scene_change else 0,
                "blend": profile.blend_on_scene_change,
                "limits": {"scene": profile.scene_change_threshold},
            },
            "gpuid": 0,
        },
    }


def generate_script(profile: Profile, source_fps: float, display_fps: float,
                    standalone_source: str | None = None,
                    matrix: str = "709") -> str:
    cfg = build_config(profile, source_fps, display_fps, standalone_source, matrix)
    # pformat, not json.dumps: the config is embedded as a Python literal inside
    # the generated script, and JSON's false/true/null are not Python names.
    literal = pprint.pformat(cfg, indent=4, width=88, sort_dicts=True)
    # Plain substitution rather than str.format, so braces in the template body
    # (dicts, sets, f-strings) never have to be escaped.
    return _HEADER.replace("{cfg}", literal) + _BODY


def write_script(profile: Profile, path: Path, source_fps: float, display_fps: float,
                 standalone_source: str | None = None, matrix: str = "709") -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        generate_script(profile, source_fps, display_fps, standalone_source, matrix),
        encoding="utf-8",
    )
    return path
